//! (the fork) The brightest stars of the Yale Bright Star Catalogue (BSC5), as the night
//! sky draws them.
//!
//! Made from brettonw/YaleBrightStarCatalog (MIT), whose data is the catalogue itself:
//! public astronomical data from NASA's Astronomical Data Center. Positions are J2000.
//!
//! Every star brighter than magnitude 4.0 is here - which is every star a constellation
//! is drawn with: the Plough's faintest is 3.3, Orion's belt 1.7 to 2.2, Cassiopeia's W
//! 2.2 to 3.4. Fainter ones are not a catalogue's work but a veil, and the sky shader draws
//! its own behind these.
//!
//! Each row is the star's unit vector in the J2000 equatorial frame (x towards right
//! ascension 0 on the equator, z towards the north celestial pole) and, in w, its colour
//! and brightness packed as `tint * 8 + (magnitude + 2)`: `tint` is one of eight steps of
//! colour temperature, from the reddest giants to the hottest blue-white, and the magnitude
//! runs from Sirius's -1.46 to 4.0.
//!
//! They are sorted by declination, and `STAR_BANDS` says where each band starts, so a ray
//! walks the stars of its own band and not all 518 of them.

